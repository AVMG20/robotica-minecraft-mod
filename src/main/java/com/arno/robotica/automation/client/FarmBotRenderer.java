package com.arno.robotica.automation.client;

import com.arno.robotica.Robotica;
import com.arno.robotica.automation.farmbot.FarmBot;
import com.arno.robotica.automation.farmbot.FarmBotItem;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.mojang.math.Axis;
import net.minecraft.client.Minecraft;
import net.minecraft.client.player.LocalPlayer;
import net.minecraft.client.renderer.LevelRenderer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.Sheets;
import net.minecraft.client.renderer.culling.Frustum;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.client.renderer.block.model.BakedQuad;
import net.minecraft.client.renderer.texture.TextureAtlas;
import net.minecraft.client.resources.model.BakedModel;
import net.minecraft.client.resources.model.ModelResourceLocation;
import net.minecraft.core.Direction;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.util.RandomSource;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.Vec3;
import net.neoforged.neoforge.client.event.ModelEvent;
import org.joml.Quaternionf;

import java.util.ArrayList;
import java.util.List;

/**
 * Stumpy and Sprout: the Mk body model plus arms that swing on every action (wind-up, slash, ease back), a small bob
 * while walking, the hurt flash, and the work area outline while you hold that robot, look at it or turned it on in
 * its menu. Models are generated by scripts/data/automation_data.py and face north.
 */
public class FarmBotRenderer extends EntityRenderer<FarmBot> {
    private static final ModelResourceLocation SAW_ARM = part("stumpy_saw_arm");
    private static final ModelResourceLocation SAW_BLADE = part("stumpy_saw_blade");
    private static final ModelResourceLocation AXE_ARM = part("stumpy_axe_arm");
    private static final ModelResourceLocation SCYTHE_ARM = part("sprout_scythe_arm");
    private static final ModelResourceLocation POUCH_ARM = part("sprout_pouch_arm");

    // Pivots in block units (model px / 16): the shoulder centres and the saw hub.
    private static final float RIGHT_X = 12.7F / 16, LEFT_X = 3.3F / 16, SHOULDER_Y = 7.25F / 16, SHOULDER_Z = 0.5F;
    private static final float BLADE_X = 14.7F / 16, BLADE_Y = 6.5F / 16;

    private static final float[] FULL = {1.0F, 1.0F, 1.0F, 1.0F};
    private static final RandomSource RANDOM = RandomSource.create();

    private final boolean stumpy;
    private final Part[] bodies = new Part[4];
    private final Part right;
    private final Part left;
    private final Part blade;
    private final Quaternionf rotation = new Quaternionf();
    private final int[] lights = new int[4];

    public FarmBotRenderer(EntityRendererProvider.Context ctx, boolean stumpy) {
        super(ctx);
        this.shadowRadius = 0.4F;
        this.stumpy = stumpy;
        for (int i = 0; i < 4; i++) bodies[i] = new Part(body(stumpy ? "stumpy" : "sprout", i + 1));
        this.right = new Part(stumpy ? SAW_ARM : SCYTHE_ARM);
        this.left = new Part(stumpy ? AXE_ARM : POUCH_ARM);
        this.blade = stumpy ? new Part(SAW_BLADE) : null;
    }

    private static ModelResourceLocation part(String name) {
        return ModelResourceLocation.standalone(Robotica.id("block/" + name));
    }

    private static ModelResourceLocation body(String name, int tier) {
        return part(name + "_mk" + tier);
    }

    public static void registerModels(ModelEvent.RegisterAdditional event) {
        for (ModelResourceLocation id : List.of(SAW_ARM, SAW_BLADE, AXE_ARM, SCYTHE_ARM, POUCH_ARM)) event.register(id);
        for (int tier = 1; tier <= 4; tier++) {
            event.register(body("stumpy", tier));
            event.register(body("sprout", tier));
        }
    }

    @Override
    public ResourceLocation getTextureLocation(FarmBot entity) {
        return TextureAtlas.LOCATION_BLOCKS;
    }

    @Override
    public void render(FarmBot bot, float yaw, float partialTick, PoseStack pose, MultiBufferSource buffers, int light) {
        float t = bot.swingTime(partialTick);
        float rightAngle = 0, leftAngle = 0, spin = 0;
        if (t >= 0) {
            if (stumpy) {
                rightAngle = swing(t, 12, -25);
                leftAngle = swing(t, 40, -75);
                spin = -540.0F * ease(t / FarmBot.SWING_TICKS);
            } else {
                switch (bot.swingKind()) {
                    case 1 -> { // plant: the pouch tips forward
                        rightAngle = swing(t, 5, -10);
                        leftAngle = swing(t, 20, -55);
                    }
                    case 2 -> { // till: a hard chop
                        rightAngle = swing(t, 40, -85);
                        leftAngle = swing(t, -8, 12);
                    }
                    default -> { // harvest
                        rightAngle = swing(t, 30, -70);
                        leftAngle = swing(t, -8, 12);
                    }
                }
            }
        }
        float walk = bot.walkAnimation.position(partialTick);
        float walkSpeed = Math.min(1.0F, bot.walkAnimation.speed(partialTick));
        float bob = Math.abs(Mth.sin(walk * 0.9F)) * 0.04F * walkSpeed;
        int overlay = LivingEntityRenderer.getOverlayCoords(bot, 0.0F);
        VertexConsumer vc = buffers.getBuffer(Sheets.cutoutBlockSheet());
        lights[0] = lights[1] = lights[2] = lights[3] = light;

        pose.pushPose();
        pose.mulPose(Axis.YP.rotationDegrees(180.0F - Mth.rotLerp(partialTick, bot.yBodyRotO, bot.yBodyRot)));
        if (bot.deathTime > 0) {
            float fall = Math.min(1.0F, Mth.sqrt((bot.deathTime + partialTick - 1.0F) / 20.0F * 1.6F));
            pose.mulPose(Axis.ZP.rotationDegrees(fall * 90.0F));
        }
        pose.translate(-0.5F, bob, -0.5F);
        draw(pose, vc, bodies[Mth.clamp(bot.tier(), 1, 4) - 1], overlay);
        pose.pushPose();
        pitch(pose, rightAngle, RIGHT_X);
        draw(pose, vc, right, overlay);
        if (blade != null) {
            if (spin != 0) pose.rotateAround(rotation.rotationX(spin * Mth.DEG_TO_RAD), BLADE_X, BLADE_Y, SHOULDER_Z);
            draw(pose, vc, blade, overlay);
        }
        pose.popPose();
        pitch(pose, leftAngle, LEFT_X);
        draw(pose, vc, left, overlay);
        pose.popPose();

        if (outlineVisible(bot)) {
            Vec3 at = bot.getPosition(partialTick);
            AABB box = bot.areaBox().move(-at.x, -at.y, -at.z);
            LevelRenderer.renderLineBox(pose, buffers.getBuffer(RenderType.lines()), box, 0.55F, 0.85F, 0.35F, 1.0F);
        }
        super.render(bot, yaw, partialTick, pose, buffers, light);
    }

    /** Pitches an arm around its shoulder; positive swings the top back, negative forward (the model faces -Z). */
    private void pitch(PoseStack pose, float degrees, float shoulderX) {
        if (degrees != 0) pose.rotateAround(rotation.rotationX(degrees * Mth.DEG_TO_RAD), shoulderX, SHOULDER_Y, SHOULDER_Z);
    }

    /** Wind-up to {@code wind} degrees, slash through to {@code slash} as it hits, then ease back to rest. */
    private static float swing(float t, float wind, float slash) {
        float hit = FarmBot.HIT_TICK;
        float slashTicks = 1.5F;
        if (t < hit) return wind * ease(t / hit);
        if (t < hit + slashTicks) return Mth.lerp(ease((t - hit) / slashTicks), wind, slash);
        return slash * (1.0F - ease((t - hit - slashTicks) / (FarmBot.SWING_TICKS - hit - slashTicks)));
    }

    private static float ease(float x) {
        x = Mth.clamp(x, 0.0F, 1.0F);
        return x * x * (3.0F - 2.0F * x);
    }

    private void draw(PoseStack pose, VertexConsumer vc, Part part, int overlay) {
        PoseStack.Pose last = pose.last();
        for (BakedQuad quad : part.quads()) vc.putBulkData(last, quad, FULL, 1.0F, 1.0F, 1.0F, 1.0F, lights, overlay, false);
    }

    /** The area shows while you hold this kind of robot, look at it, or turned the outline on in its menu. */
    private boolean outlineVisible(FarmBot bot) {
        if (bot.showArea()) return true;
        Minecraft mc = Minecraft.getInstance();
        LocalPlayer player = mc.player;
        if (player == null) return false;
        if (holdsSameKind(player.getMainHandItem(), bot) || holdsSameKind(player.getOffhandItem(), bot)) {
            return player.distanceToSqr(bot) < 64.0 * 64.0;
        }
        return mc.crosshairPickEntity == bot;
    }

    private static boolean holdsSameKind(ItemStack stack, FarmBot bot) {
        return stack.getItem() instanceof FarmBotItem item && item.entityType() == bot.getType();
    }

    @Override
    public boolean shouldRender(FarmBot bot, Frustum frustum, double camX, double camY, double camZ) {
        return super.shouldRender(bot, frustum, camX, camY, camZ) || (outlineVisible(bot) && frustum.isVisible(bot.areaBox()));
    }

    /** One baked model and its quads, refreshed when the models are reloaded. */
    private static final class Part {
        private final ModelResourceLocation id;
        private BakedModel model;
        private List<BakedQuad> quads = List.of();

        Part(ModelResourceLocation id) {
            this.id = id;
        }

        List<BakedQuad> quads() {
            BakedModel current = Minecraft.getInstance().getModelManager().getModel(id);
            if (current != model) {
                model = current;
                List<BakedQuad> all = new ArrayList<>();
                for (Direction dir : Direction.values()) all.addAll(current.getQuads(null, dir, RANDOM));
                all.addAll(current.getQuads(null, null, RANDOM));
                quads = all;
            }
            return quads;
        }
    }
}
